def _make(title, category, level, instructor, desc, core_lines, quiz):
    p = PACKS.get(category, PACKS["Crop Management"])
    return {
        "title": title,
        "category": category,
        "level": level,
        "instructor": instructor,
        "description": desc,
        "duration_weeks": 3,
        "core_content": "\n".join(core_lines),
        "tools_materials": "\n".join(p["tools"]),
        "safety_tips": "\n".join(p["safety"]),
        "quiz": quiz,
    }


