COURSES = []


def add_courses(category, level, items, img=None):
    for i, it in enumerate(items):
        if isinstance(it, tuple):
            title, desc, core = it
            quiz = None
        else:
            title = it["title"]
            desc = it["description"]
            core = it["core"]
            quiz = it.get("quiz")
        instructor = INSTRUCTORS[(len(COURSES) + i) % len(INSTRUCTORS)]
        course = _make(title, category, level, instructor, desc, core, quiz)
        COURSES.append(course)


