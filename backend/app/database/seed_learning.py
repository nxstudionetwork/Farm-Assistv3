def _upsert_course(db, data):
    """Insert a course (and its lesson + quiz) if it does not yet exist by title."""
    existing = db.query(Course).filter(Course.title == data["title"]).first()
    if existing:
        return None

    course = Course(
        course_id=generate_id("FA-CRS", db, Course),
        title=data["title"],
        description=data["description"],
        category=data["category"],
        level=data["level"],
        duration_weeks=data.get("duration_weeks"),
        language="English",
        instructor=data["instructor"],
        video_url=data.get("video_url") or "",
        core_content=data.get("core_content"),
        tools_materials=data.get("tools_materials"),
        safety_tips=data.get("safety_tips"),
        total_lessons=1,
        is_published=True,
    )
    db.add(course)
    db.flush()

    # Single tutorial lesson holds the core content and hosts the quiz.
    lesson = CourseLesson(
        lesson_id=f"T{course.course_id.split('-')[-1]}",
        course_id=course.id,
        title=f"{data['title']} - Tutorial",
        description=data.get("core_content"),
        content=data.get("core_content"),
        content_type="text",
        order_index=0,
        duration_minutes=20,
        is_published=True,
    )
    db.add(lesson)
    db.flush()

    quiz = data.get("quiz") or [
        _q(
            f"What is the first practical step recommended in '{data['title']}'?",
            ["Prepare/select correctly for your field", "Skip all field preparation",
             "Immediately harvest", "Stop all irrigation"],
            0,
            "Every practical course begins with proper selection and preparation.",
        ),
        _q(
            "Why are safety and tool preparation important?",
            ["To work safely and effectively", "To raise costs", "To slow down work", "They are not important"],
            0, "Preparing tools and following safety protects both you and the crop.",
        ),
        _q(
            "What should you do when a problem appears mid-season?",
            ["Scout, identify and act early", "Ignore it", "Harvest early", "Use extra everything"],
            0, "Early scouting and correct identification let you manage problems in time.",
        ),
    ]

    for i, q in enumerate(quiz):
        qid = f"Q{course.course_id.split('-')[-1]}-{i+1}"
        db.add(LearningQuestion(
            question_id=qid,
            tutorial_id=lesson.id,
            course_id=course.id,
            question=q["question"],
            option_1=q["options"][0],
            option_2=q["options"][1],
            option_3=q["options"][2],
            option_4=q["options"][3],
            correct_answer=q["correct"],
            explanation=q.get("explanation", ""),
            order_index=i,
        ))

    return course


def seed_learning(db):
    """Idempotently seed learning courses. Returns a summary dict."""
    created = 0
    existing = 0
    for data in COURSES:
        course = _upsert_course(db, data)
        if course is not None:
            created += 1
        else:
            existing += 1
    db.commit()
    total = db.query(Course).count()
    return {
        "created": created,
        "already_existing": existing,
        "total_courses": total,
    }


if __name__ == "__main__":
    db = SessionLocal()
