# Shared step templates reused across courses in a category to keep every course
# practical and concise (topic title + short description).
#
# _MAKE builds a full course record given topic + category-level content packs.
# Each course gets:
#   - title / description
#   - core_content (newline separated practical steps)
#   - tools_materials (newline separated list)
#   - safety_tips (newline separated list)
#   - quiz (4 questions, each 4 options + correct index + explanation)


def _q(question, opts, correct, explanation):
    """Build a 4-option quiz question."""
    while len(opts) < 4:
        opts.append(opts[-1] if opts else "None of the above")
    return {
        "question": question,
        "options": opts[:4],
        "correct": correct,
        "explanation": explanation,
    }


