def _generated_products() -> list:
    """Deterministically expand standard lending lines across lenders/regions."""
    products = []
    serial = 1
    for li, (lender, lender_type, kind) in enumerate(LENDERS):
        for ti, t in enumerate(GENERATED_TEMPLATES):
            rate = float(t["base_rate"])
            if t["government_backed"]:
                rate_str = "From {:.1f}% p.a. (effective 4% for timely repayment under interest subvention)".format(rate)
            else:
                rate = round(rate + (li % 6) * 0.25, 2)
                rate_str = "From {:.2f}% p.a. (repo-linked, as published)".format(rate)

            if kind == "regional":
                state = REGIONAL_STATES[li % len(REGIONAL_STATES)]
            else:
                state = "All India"

            scale = 1 + (li % 5) * 0.15
            max_amount = int(round(float(t["max_amount"]) * scale / 1000.0) * 1000)

            name = "{} {}".format(lender, t["name"])
            if lender in ("SBI",) and t["name"].startswith("Kisan"):
                name = "{} {}".format(lender, t["name"])

            products.append({
                "product_id": "FA-LOANP-{:06d}".format(200000 + serial),
                "lender": lender,
                "lender_type": lender_type,
                "name": name,
                "category": t["category"],
                "loan_type": t["loan_type"],
                "description": t["description"],
                "min_amount": t["min_amount"],
                "max_amount": max_amount,
                "interest_rate": rate_str,
                "interest_rate_annual": rate,
                "tenure_months": t["tenure_months"],
                "tenure_text": t["tenure_text"],
                "repayment_frequency": t["repayment_frequency"],
                "eligibility": t["eligibility"],
                "collateral_requirement": t["collateral_requirement"],
                "required_documents": list(t["required_documents"]),
                "application_method": "Apply through {} agri finance channel (branch / digital)".format(lender),
                "fees": None,
                "official_url": None,
                "source": SRC,
                "source_url": None,
                "state": state,
                "government_backed": t["government_backed"],
                "scheme_name": t["scheme"],
                "status": "active",
                "last_verified_at": LAST_VERIFIED,
            })
            serial += 1
    return products


