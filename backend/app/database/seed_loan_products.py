def seed_loan_products(db: Session) -> int:
    """Idempotent seeder. Returns the number of new products inserted."""
    from app.models.government import GovernmentScheme

    by_id = {p.product_id: p for p in db.query(AgriculturalLoanProduct).all()}
    created = 0
    for item in PRODUCTS:
        product_id = item["product_id"]
        existing = by_id.get(product_id)
        scheme = None
        if item.get("scheme_name"):
            scheme = (
                db.query(GovernmentScheme)
                .filter(
                    GovernmentScheme.name.ilike(f"%{item['scheme_name']}%"),
                    GovernmentScheme.status == "active",
                )
                .first()
            )
        row = existing
        if row is None:
            row = AgriculturalLoanProduct(product_id=product_id)
            db.add(row)
            created += 1
        for key, value in item.items():
            if key == "scheme_name":
                continue
            setattr(row, key, value)
        row.scheme_id = scheme.id if scheme else None
        row.last_verified_at = LAST_VERIFIED
        row.status = "active"
    db.commit()
    return created